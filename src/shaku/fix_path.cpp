// fix_path.cpp -- path fix: units laid inside a narrow stretch of their path (gate, doorway, ramp)
// are released beyond it; men queueing for a corner take radius lanes, lead the turn and are not
// crowd-damped there.
//
// From ShakuEight/Shogun2-fix (fixes/pathfix/release/pathfix_release.cpp, release 1.0 from dev build
// v42), Copyright 2026 ShakuEight, Apache License 2.0 (third_party/LICENSE-APACHE-2.0). Ported to this
// project: the fix itself is unchanged (variant G, always on, the five hooks it needs); the release
// source already has no keys, tones, capture, run folders, crash filter or test exports. The SEH
// block in LeadTheTurn is replaced by the guarded reads of gamemem.h, the generated detour symbols
// are prefixed path_, and the install / remove log lines go to tws2fix.log.
//
// What it does (ShakuEight's description): when a unit's formation block would be laid inside a
// narrow stretch of its path, the block is laid past the end of that stretch, so the men run through
// as a column and re-form beyond it; men queueing for a corner take wider lines by rank (radius
// lanes), aim further round the corner at a free point (lead the turn) and are not slowed by crowd
// damping there. Park release (dev v42): after the formation was laid past a narrow stretch, a unit
// whose leader had reached his place short of the path end could stay "not finished" for good when
// men on go-to orders could not reach their places (several units sent to one spot), so a
// shift-queued next order never started. The block front now goes past the path end in that case,
// which is the game's own end-of-move state, as it would be without the fix.
//
// Engine decode (ShakuEight's notes, Ghidra names in the analysed image, base 0x10000000):
// - FUN_101bc880 (ECX = unit path controller): the orders / laying call, once per game second per
//   unit. ctrl+0x04 = unit (soldier count +0x18, array +0x1C), ctrl+0x30 = leader index (0 right
//   after an order), ctrl+0x34 = current path node, ctrl+0x38 = t along it. Game clock at
//   [[ctrl+0x14]+8]+0x50 (engine tick = 0.1 game s). A path node: next at +0x08, widths at +0x74 /
//   +0x78, segment endpoints at +0x80..+0x8F.
// - FUN_103670a0 (ECX = cursor {node, t}, arg1 = distance): advances the block front along the
//   path; only the call from 0x101BC983 (return address RVA 0x1BC988) lays the formation.
// - FUN_103df3f0 (EBX = soldier): the soldier's replan. At +0xE1 (0x103DF4D1) the request radius w
//   sits at request+0x2C, the destination copied from soldier+0x420 at request+0x18; at +0x2D0
//   (0x103DF6C0) the funnel FUN_10394e80 has chosen the waypoint (buffer at hook ESP+0x44, returned
//   in EAX) for the corner portal (link +0x10, type +0x08, edge +0x20; edge twin +0x08, vertex
//   +0x0C/+0x10, offset vector +0x24/+0x28). Soldier: position +0x48/+0x50, radius object +0x3CC
//   (half-width at +0x50), slot +0x420, parked flags +0x384 / +0x308. The corner apex candidates
//   come from the game's endpoint helpers FUN_10393000 (left) and FUN_103a0080 (right).
// - FUN_10367600 (ECX = soldier): the integrator; byte +0xD6 is the crowd damping switch, move D at
//   +0xD8 / +0xE0.
//
// Safety: all five patch sites and the two endpoint helpers are byte-checked against the analysed
// Empire.Retail.dll before anything is written; on any difference nothing is installed. At run time
// the hook frame, the corner geometry, the apex match and the radius request are checked (first
// FIX_CHECK_CALLS of each); a failure past the allowance switches the fix off for the session.

